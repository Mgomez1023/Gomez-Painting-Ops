@pytest.fixture
def anyio_backend() -> str:
    return "asyncio"


class FakeCampaignContentQueueSheetsService:
    def __init__(self, status: str = "Needs Review", approved: str = "No") -> None:
        self.item = CampaignContentQueueItem(
            content_id="CCQ-1001-facebook",
            campaign_id="CAMP-1001",
            platform="Facebook",
            draft_text="Facebook campaign draft",
            cta="Request a quote",
            landing_page_url="https://gomezpainting.example/quote",
            status=status,
            approved=approved,
            published="No",
            created_at="2026-04-28T00:00:00Z",
            published_at=None,
            notes="Generated by CampaignAgent",
        )
        self.updated_item: CampaignContentQueueItem | None = None

    def list_campaign_content_queue_items(self) -> list[CampaignContentQueueItem]:
        return [
            self.item,
            self.item.model_copy(
                update={
                    "content_id": "CCQ-1001-nextdoor",
                    "platform": "Nextdoor",
                    "draft_text": "Nextdoor draft",
                }
            ),
        ]

    def get_campaign_content_queue_item_by_id(self, content_id: str) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None
        return self.item

    def approve_campaign_content_queue_item(self, content_id: str) -> CampaignContentQueueItem | None:
        return self._update(content_id=content_id, status="Approved", approved="Yes", published="No")

    def reject_campaign_content_queue_item(self, content_id: str) -> CampaignContentQueueItem | None:
        return self._update(content_id=content_id, status="Rejected", approved="No", published="No")

    def mark_campaign_content_queue_item_published(self, content_id: str) -> CampaignContentQueueItem | None:
        return self._update(
            content_id=content_id,
            status="Published",
            approved="Yes",
            published="Yes",
            published_at="2026-04-28T01:00:00Z",
        )

    def publish_campaign_content_queue_item(
        self,
        content_id: str,
        published_at: str,
        notes: str,
        external_post_id: str | None = None,
        published_url: str | None = None,
    ) -> CampaignContentQueueItem | None:
        return self._update(
            content_id=content_id,
            status="Published",
            approved="Yes",
            published="Yes",
            published_at=published_at,
            notes=notes,
            external_post_id=external_post_id,
            published_url=published_url,
        )

    def schedule_campaign_content_queue_item(
        self,
        content_id: str,
        scheduled_at: str,
    ) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None

        self.updated_item = self.item.model_copy(
            update={
                "scheduled_at": scheduled_at,
                "published": "No",
            }
        )
        return self.updated_item

    def _update(
        self,
        content_id: str,
        status: str,
        approved: str,
        published: str,
        published_at: str | None = None,
        notes: str | None = None,
        external_post_id: str | None = None,
        published_url: str | None = None,
    ) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None

        update_payload = {
            "status": status,
            "approved": approved,
            "published": published,
            "published_at": published_at,
        }
        if notes is not None:
            update_payload["notes"] = notes
        if external_post_id is not None:
            update_payload["external_post_id"] = external_post_id
        if published_url is not None:
            update_payload["published_url"] = published_url

        self.updated_item = self.item.model_copy(update=update_payload)
        return self.updated_item


@pytest.mark.anyio
async def test_list_campaign_content_queue_items_returns_queue_items() -> None:
    async def override_sheets_service() -> FakeCampaignContentQueueSheetsService:
        return FakeCampaignContentQueueSheetsService()

    app.dependency_overrides[get_sheets_service] = override_sheets_service
    transport = ASGITransport(app=app)

    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.get("/campaign-content-queue")

    app.dependency_overrides.clear()

    assert response.status_code == 200
    data = response.json()
    assert len(data) == 2
    assert [item["content_id"] for item in data] == ["CCQ-1001-facebook", "CCQ-1001-nextdoor"]
    assert [CampaignContentQueueItem.model_validate(item).platform for item in data] == ["Facebook", "Nextdoor"]


