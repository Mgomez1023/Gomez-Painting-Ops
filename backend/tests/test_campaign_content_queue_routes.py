@pytest.mark.anyio
async def test_publish_campaign_content_queue_item_publishes_approved_item_in_mock_mode() -> None:
    fake_sheets_service = FakeCampaignContentQueueSheetsService(status="Approved", approved="Yes")
    publisher_service = PublisherService(app_settings=Settings(publisher_mode="mock"))

    async def override_sheets_service() -> FakeCampaignContentQueueSheetsService:
        return fake_sheets_service

    async def override_publisher_service() -> PublisherService:
        return publisher_service

    app.dependency_overrides[get_sheets_service] = override_sheets_service
    app.dependency_overrides[get_publisher_service] = override_publisher_service
    transport = ASGITransport(app=app)

    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.post("/campaign-content-queue/CCQ-1001-facebook/publish")

    app.dependency_overrides.clear()

    assert response.status_code == 200
    parsed_response = CampaignContentPublishResponse.model_validate(response.json())
    assert parsed_response.publish_result.external_post_id == "mock-facebook-CCQ-1001-facebook"
    assert parsed_response.publish_result.published_url.endswith("/mock-facebook-CCQ-1001-facebook")
    assert parsed_response.queue_item.status == "Published"
    assert parsed_response.queue_item.approved == "Yes"
    assert parsed_response.queue_item.published == "Yes"
    assert parsed_response.queue_item.published_at is not None
    assert parsed_response.queue_item.external_post_id == "mock-facebook-CCQ-1001-facebook"
    assert parsed_response.queue_item.published_url is not None
    assert "external_post_id=mock-facebook-CCQ-1001-facebook" in parsed_response.queue_item.notes
    assert fake_sheets_service.updated_item is not None


