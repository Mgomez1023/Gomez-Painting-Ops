def test_google_business_verify_uses_newer_account_and_location_apis() -> None:
    requests: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        requests.append(request)
        if str(request.url) == "https://oauth2.googleapis.com/token":
            return httpx.Response(200, json={"access_token": "access-token"})
        if str(request.url) == "https://mybusinessaccountmanagement.googleapis.com/v1/accounts":
            return httpx.Response(200, json={"accounts": [{"name": "accounts/account-123"}]})
        assert str(request.url).startswith(
            "https://mybusinessbusinessinformation.googleapis.com/v1/accounts/account-123/locations"
        )
        return httpx.Response(200, json={"locations": [{"name": "locations/location-456"}]})

    publisher = GoogleBusinessPublisher(
        app_settings=google_business_settings(),
        http_client_factory=lambda: http_client_factory(httpx.MockTransport(handler)),
    )

    result = publisher.verify_credentials()

    assert result["ok"] is True
    assert result["account_verification_api"] == "https://mybusinessaccountmanagement.googleapis.com/v1"
    assert result["location_verification_api"] == "https://mybusinessbusinessinformation.googleapis.com/v1"
    assert result["local_posts_publish_api"] == "https://mybusiness.googleapis.com/v4"
    assert [str(request.url).split("?")[0] for request in requests] == [
        "https://oauth2.googleapis.com/token",
        "https://mybusinessaccountmanagement.googleapis.com/v1/accounts",
        "https://mybusinessbusinessinformation.googleapis.com/v1/accounts/account-123/locations",
    ]


