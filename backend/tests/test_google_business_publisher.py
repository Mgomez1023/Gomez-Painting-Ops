def queue_item(**overrides: Any) -> CampaignContentQueueItem:
    scheduled_at = (datetime.now(timezone.utc) - timedelta(minutes=5)).isoformat(timespec="seconds").replace(
        "+00:00",
        "Z",
    )
    values: dict[str, Any] = {
        "content_id": "CCQ-1001-google-business",
        "campaign_id": "CAMP-1001",
        "platform": "Google Business",
        "draft_text": "Fresh interior paint completed in Oak Park.",
        "cta": "Request a quote",
        "landing_page_url": "https://gomezpainting.example/quote",
        "image_filename": "room.jpg",
        "image_path": "https://cdn.example.com/room.jpg",
        "status": "Approved",
        "approved": "Yes",
        "published": "No",
        "created_at": "2026-04-28T00:00:00Z",
        "scheduled_at": scheduled_at,
        "notes": "Generated by CampaignAgent",
    }
    values.update(overrides)
    return CampaignContentQueueItem(**values)


class FakeSheetsService:
    def __init__(self, item: CampaignContentQueueItem) -> None:
        self.item = item
        self.updated_item: CampaignContentQueueItem | None = None

    def list_due_campaign_content_queue_items(self) -> list[CampaignContentQueueItem]:
        return [self.item]

    def get_campaign_content_queue_item_by_id(self, content_id: str) -> CampaignContentQueueItem | None:
        return self.item if content_id == self.item.content_id else None

    def publish_campaign_content_queue_item(
        self,
        content_id: str,
        published_at: str,
        notes: str,
        external_post_id: str | None = None,
        published_url: str | None = None,
    ) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None
        self.updated_item = self.item.model_copy(
            update={
                "status": "Published",
                "approved": "Yes",
                "published": "Yes",
                "published_at": published_at,
                "publish_attempts": self.item.publish_attempts + 1,
                "last_publish_error": None,
                "external_post_id": external_post_id,
                "published_url": published_url,
                "notes": notes,
            }
        )
        return self.updated_item

    def record_campaign_content_publish_failure(
        self,
        content_id: str,
        error_message: str,
    ) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None
        self.updated_item = self.item.model_copy(
            update={
                "publish_attempts": self.item.publish_attempts + 1,
                "last_publish_error": error_message,
                "published": "No",
            }
        )
        return self.updated_item

    def record_campaign_content_publish_result(
        self,
        content_id: str,
        status: str,
        published: str,
        published_at: str | None,
        notes: str,
        external_post_id: str | None = None,
        published_url: str | None = None,
        last_publish_error: str | None = None,
    ) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None
        self.updated_item = self.item.model_copy(
            update={
                "status": status,
                "published": published,
                "published_at": published_at,
                "publish_attempts": self.item.publish_attempts + 1,
                "last_publish_error": last_publish_error,
                "external_post_id": external_post_id,
                "published_url": published_url,
                "notes": notes,
            }
        )
        return self.updated_item

    def record_campaign_content_manual_fallback(
        self,
        content_id: str,
        error_message: str,
        copy_ready_package: str,
    ) -> CampaignContentQueueItem | None:
        if content_id != self.item.content_id:
            return None
        notes = f"{self.item.notes}\n\n{copy_ready_package}" if self.item.notes else copy_ready_package
        self.updated_item = self.item.model_copy(
            update={
                "status": "Ready for Manual Post",
                "publish_attempts": self.item.publish_attempts + 1,
                "last_publish_error": error_message,
                "published": "No",
                "notes": notes,
            }
        )
        return self.updated_item


def http_client_factory(handler: httpx.MockTransport) -> httpx.Client:
    return httpx.Client(transport=handler)


def form_data(request: httpx.Request) -> dict[str, str]:
    parsed = parse_qs(request.content.decode())
    return {key: values[0] for key, values in parsed.items()}


