class FakeSheetsService:
    def __init__(
        self,
        jobs: list[CompletedJob],
        existing_queue_items: list[ContentQueueItem] | None = None,
    ) -> None:
        self.jobs = jobs
        self.existing_queue_items = existing_queue_items or []
        self.saved_queue_items: list[ContentQueueItem] = []
        self.append_count = 0

    def get_completed_job_by_id(self, job_id: str) -> CompletedJob | None:
        for job in self.jobs:
            if job.job_id == job_id:
                return job
        return None

    def get_content_queue_items_by_job_id(self, job_id: str) -> list[ContentQueueItem]:
        return [item for item in self.existing_queue_items if item.job_id == job_id]

    def save_content_draft_to_queue(self, job_id: str, draft: ContentDraft) -> list[ContentQueueItem]:
        self.append_count += 4
        self.saved_queue_items = [
            ContentQueueItem(
                content_id=f"CQ-test-{platform.lower().replace(' ', '-')}",
                job_id=job_id,
                platform=platform,
                draft_text=draft_text,
                created_at="2026-04-28T00:00:00Z",
                notes="Generated by ContentAgent",
            )
            for platform, draft_text in [
                ("Facebook", draft.facebook_post),
                ("Google Business", draft.google_business_post),
                ("Instagram", draft.instagram_caption),
                ("Review Request", draft.review_request_text),
            ]
        ]
        return self.saved_queue_items


class MissingConfigSheetsService:
    def get_completed_job_by_id(self, job_id: str) -> CompletedJob | None:
        raise SheetsConfigurationError("Google Sheets is not configured.")


def build_existing_queue_items(job_id: str = "JOB-1001") -> list[ContentQueueItem]:
    return [
        ContentQueueItem(
            content_id=f"CQ-existing-{platform.lower().replace(' ', '-')}",
            job_id=job_id,
            platform=platform,
            draft_text=f"Existing {platform} draft.",
            status="Needs Review",
            approved="No",
            published="No",
            created_at="2026-04-28T00:00:00Z",
            notes="Generated by ContentAgent",
        )
        for platform in ["Facebook", "Google Business", "Instagram", "Review Request"]
    ]


