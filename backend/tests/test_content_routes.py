@pytest.mark.anyio
async def test_generate_content_from_job_save_returns_draft_and_four_queue_items() -> None:
    job = CompletedJob(
        job_id="JOB-1001",
        customer="Maria R.",
        job_type="Interior Paint",
        location="Oak Park",
        date_completed="March 2026",
        photos_uploaded=True,
        notes="Living room repaint with trim refresh.",
    )
    fake_sheets_service = FakeSheetsService([job])

    async def override_sheets_service() -> FakeSheetsService:
        return fake_sheets_service

    app.dependency_overrides[get_sheets_service] = override_sheets_service
    transport = ASGITransport(app=app)

    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.post("/content/generate-from-job/JOB-1001/save")

    app.dependency_overrides.clear()

    assert response.status_code == 200
    data = response.json()
    parsed_response = ContentQueueSaveResponse.model_validate(data)

    assert "content_draft" in data
    assert len(data["queue_items"]) == 4
    assert len(parsed_response.queue_items) == 4
    assert [item["platform"] for item in data["queue_items"]] == [
        "Facebook",
        "Google Business",
        "Instagram",
        "Review Request",
    ]
    assert {item["status"] for item in data["queue_items"]} == {"Needs Review"}
    assert {item["approved"] for item in data["queue_items"]} == {"No"}
    assert {item["published"] for item in data["queue_items"]} == {"No"}
    assert len(fake_sheets_service.saved_queue_items) == 4
    assert fake_sheets_service.append_count == 4


@pytest.mark.anyio
async def test_generate_content_from_job_save_returns_409_when_drafts_already_exist() -> None:
    job = CompletedJob(
        job_id="JOB-1001",
        customer="Maria R.",
        job_type="Interior Paint",
        location="Oak Park",
        date_completed="March 2026",
        photos_uploaded=True,
        notes="Living room repaint with trim refresh.",
    )
    fake_sheets_service = FakeSheetsService([job], existing_queue_items=build_existing_queue_items())

    async def override_sheets_service() -> FakeSheetsService:
        return fake_sheets_service

    app.dependency_overrides[get_sheets_service] = override_sheets_service
    transport = ASGITransport(app=app)

    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.post("/content/generate-from-job/JOB-1001/save")

    app.dependency_overrides.clear()

    assert response.status_code == 409
    data = response.json()
    parsed_response = ContentQueueConflictResponse.model_validate(data)

    assert data["detail"] == (
        "Drafts already exist for this job. Review them in Content Queue instead of generating duplicates."
    )
    assert len(parsed_response.existing_queue_items) == 4
    assert [item["platform"] for item in data["existing_queue_items"]] == [
        "Facebook",
        "Google Business",
        "Instagram",
        "Review Request",
    ]
    assert fake_sheets_service.saved_queue_items == []
    assert fake_sheets_service.append_count == 0


